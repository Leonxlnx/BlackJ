const dict = { de, en };

export function translate(lang, key, params) {
  let s = (dict[lang] && dict[lang][key]) ?? de[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

/** Hook: const t = useT(); t('ws.compile') */
export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (key, params) => translate(lang, key, params);
}

export function formatNumber(lang, n) {
  return new Intl.NumberFormat(lang === 'en' ? 'en-GB' : 'de-DE').format(n);
}

export function formatCost(lang, dollars) {
  if (lang === 'en') return '$' + dollars.toFixed(dollars < 0.01 ? 4 : 2);
  if (dollars < 0.01) return new Intl.NumberFormat('de-DE', { maximumFractionDigits: 2 }).format(dollars * 100) + ' ct';
  return new Intl.NumberFormat('de-DE', { style: 'currency', currency: 'USD' }).format(dollars);
}

export function relativeDay(lang, iso) {
  const then = new Date(iso);
  const now = new Date();
  const days = Math.round((new Date(now.toDateString()) - new Date(then.toDateString())) / 86400000);
  if (days <= 0) return translate(lang, 'when.today');
  if (days === 1) return translate(lang, 'when.yesterday');
  return translate(lang, 'when.days', { n: days });
}
